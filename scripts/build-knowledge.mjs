#!/usr/bin/env node
/**
 * Builds the knowledge file the "Ask about me" box answers from.
 *
 * docs/ASK-ABOUT-ME.md: the site content is small, so the whole file is sent
 * with every request. No vector database, no embeddings, no RAG.
 *
 * Every line still holding an `[ADD` or `[CHECK` placeholder is stripped, so the
 * model can never read a placeholder back to a visitor as if it were a fact.
 * Notes addressed to Aayush (markdown blockquotes) are stripped for the same
 * reason — they are instructions to him, not facts about him.
 *
 * Output is a TypeScript module rather than a text file so it bundles into the
 * serverless function instead of relying on the filesystem at runtime.
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "content", "generated");

const PLACEHOLDER = /\[(ADD|CHECK)\b/;

/**
 * A line can lose part of itself to a placeholder without losing its meaning.
 * `**Links:** Read case study · Live plugin [ADD URL] · nestulabs.com` should
 * keep the two real links; `**Metrics:** [ADD] · [ADD]` should disappear whole.
 * So: split the value on the interpunct, drop the dead segments, and drop the
 * line only when nothing factual is left.
 */
const LABELLED = /^(\s*(?:[-*]\s+)?)(\*\*[^*]+\*\*:?\s*)?([\s\S]*)$/;
const HOLE = "\u0000";

function hasSubstance(text) {
  return /[A-Za-z0-9]/.test(text.split(HOLE).join(""));
}

function clean(markdown) {
  const kept = [];
  let dropped = 0;

  for (const raw of markdown.split("\n")) {
    const line = raw.replace(/\s+$/, "");

    // Notes written to Aayush, not facts about him. Checked before the
    // placeholder rule so a bracket inside a note cannot leak through.
    if (line.trimStart().startsWith(">")) continue;
    // Table separator rows and code fences carry no meaning as plain text.
    if (/^\s*\|[\s|:-]+\|\s*$/.test(line)) continue;
    if (/^```/.test(line)) continue;

    if (!PLACEHOLDER.test(line)) {
      kept.push(line);
      continue;
    }

    dropped += 1;

    // A table row loses too much structure to be worth salvaging.
    if (line.trimStart().startsWith("|")) continue;

    const punched = line.replace(/\[(ADD|CHECK)[^\]]*\]/g, HOLE);
    const match = LABELLED.exec(punched);
    const prefix = match?.[1] ?? "";
    const label = match?.[2] ?? "";
    const value = match?.[3] ?? "";

    const segments = value
      .split("·")
      .map((segment) => segment.trim())
      .filter((segment) => hasSubstance(segment))
      .map((segment) => segment.split(HOLE).join("").replace(/\s{2,}/g, " ").trim())
      .filter((segment) => segment.length > 0);

    if (segments.length === 0) continue;

    kept.push(
      `${prefix}${label}${segments.join(" · ")}`
        .replace(/\s+([.,;:])/g, "$1")
        .replace(/\s{2,}/g, " ")
        .trimEnd(),
    );
  }

  return { text: kept.join("\n"), dropped };
}

/** CONTENT.md opens with instructions for whoever edits it. Not facts. */
function dropEditorPreamble(markdown) {
  const start = markdown.indexOf("Rules for using this file:");
  if (start === -1) return markdown;
  const end = markdown.indexOf("\n---", start);
  if (end === -1) return markdown;
  return markdown.slice(0, start) + markdown.slice(end + 4);
}

/** Drop mermaid blocks — the diagrams are described in prose elsewhere. */
function stripMermaid(markdown) {
  return markdown.replace(/```mermaid[\s\S]*?```/g, "");
}

function collapse(text) {
  return text.replace(/\n{3,}/g, "\n\n").trim();
}

async function main() {
  await mkdir(outDir, { recursive: true });

  const parts = [];
  let droppedTotal = 0;

  const contentPath = join(root, "content", "CONTENT.md");
  const content = clean(dropEditorPreamble(stripMermaid(await readFile(contentPath, "utf8"))));
  droppedTotal += content.dropped;
  parts.push(collapse(content.text));

  const caseDir = join(root, "content", "case-studies");
  const files = (await readdir(caseDir)).filter((name) => name.endsWith(".md")).sort();
  for (const name of files) {
    const study = clean(stripMermaid(await readFile(join(caseDir, name), "utf8")));
    droppedTotal += study.dropped;
    parts.push(`# Case study: ${name.replace(/\.md$/, "")}\n\n${collapse(study.text)}`);
  }

  const knowledge = collapse(parts.join("\n\n---\n\n"));

  const systemPrompt = (await readFile(join(root, "content", "ask-system-prompt.md"), "utf8")).trim();
  if (!systemPrompt.includes("{{KNOWLEDGE}}")) {
    throw new Error("content/ask-system-prompt.md no longer contains {{KNOWLEDGE}}.");
  }

  const literal = (value) => JSON.stringify(value);

  await writeFile(
    join(outDir, "knowledge.ts"),
    [
      "// Generated by scripts/build-knowledge.mjs — do not edit by hand.",
      "// Rebuilt on every deploy from content/CONTENT.md and content/case-studies/*.md,",
      "// with every [ADD] / [CHECK] placeholder removed.",
      "",
      `export const knowledge = ${literal(knowledge)};`,
      "",
      `export const systemPromptTemplate = ${literal(systemPrompt)};`,
      "",
      "/** The full system prompt, knowledge inlined. */",
      "export const systemPrompt = systemPromptTemplate.replace(\"{{KNOWLEDGE}}\", knowledge);",
      "",
      `export const knowledgeChars = ${knowledge.length};`,
      "",
    ].join("\n"),
    "utf8",
  );

  // A plain-text copy, handy for eyeballing what the model actually sees.
  await writeFile(join(outDir, "knowledge.txt"), `${knowledge}\n`, "utf8");

  console.log(
    `  knowledge.ts    ${knowledge.length} chars (~${Math.round(knowledge.length / 4)} tokens), ` +
      `${droppedTotal} placeholder lines removed`,
  );

  if (/\[(ADD|CHECK)\b/.test(knowledge)) {
    throw new Error("A placeholder survived into the knowledge file.");
  }
}

main().catch((error) => {
  console.error(`\nKnowledge build failed: ${error.message}\n`);
  process.exit(1);
});
